function renderProjects(filter = "all") {
  const filtered =
    filter === "all"
      ? projects
      : projects.filter((project) => project.category === filter);

  projectsGrid.innerHTML = filtered
    .map(
      (project, index) => `
    <article class="card project reveal stagger-item" style="transition-delay:${index * 0.08}s">
      <div class="project__image">
        <img src="${project.image}" alt="${project.title}" />
      </div>
      <div class="project__body">
        <h3>${project.title}</h3>
        <p>${project.description}</p>
        <div class="tags">
          ${project.tags.map((tag) => `<span class="tag">${tag}</span>`).join("")}
        </div>
        <button class="btn btn--secondary open-project" data-title="${project.title}" data-description="${project.description}" data-image="${project.image}" data-link="${project.link}" data-tags='${JSON.stringify(project.tags)}'>Preview</button>
      </div>
    </article>
  `,
    )
    .join("");
  observeReveals();
  bindProjectButtons();
}

function bindProjectButtons() {
  document.querySelectorAll(".open-project").forEach((button) => {
    button.addEventListener("click", () => {
      modalImage.src = button.dataset.image;
      modalTitle.textContent = button.dataset.title;
      modalDescription.textContent = button.dataset.description;
      modalLink.href = button.dataset.link;
      const tags = JSON.parse(button.dataset.tags || "[]");
      modalTags.innerHTML = tags.map((tag) => `<span>${tag}</span>`).join("");
      modal.classList.add("open");
      document.body.classList.add("nav-open");
    });
  });
}

function closeModal() {
  modal.classList.remove("open");
  document.body.classList.remove("nav-open");
}

modalClose.addEventListener("click", closeModal);
modalOverlay.addEventListener("click", closeModal);

document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeModal();
});

